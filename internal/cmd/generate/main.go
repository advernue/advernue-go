// Command generate reads spec/openapi.json and emits types_gen.go,
// services_gen.go and CONTRIBUTING.md.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type schema = map[string]any

type gen struct {
	comps  schema
	types  map[string]string // go type name -> declaration
	order  []string
	skip   map[string]bool // hand-written types
	consts bytes.Buffer
}

func main() {
	specPath := flag.String("spec", "spec/openapi.json", "OpenAPI spec")
	out := flag.String("out", ".", "output directory")
	flag.Parse()
	raw, err := os.ReadFile(*specPath)
	check(err)
	var spec schema
	check(json.Unmarshal(raw, &spec))
	g := &gen{comps: spec["components"].(schema)["schemas"].(schema), types: map[string]string{}, skip: map[string]bool{"Money": true, "Error": true}}

	// Component schemas first, in sorted order for stable output.
	names := keys(g.comps)
	for _, n := range names {
		if g.skip[n] {
			continue
		}
		g.declare(n, g.comps[n].(schema))
	}

	svc := g.services(spec)
	var types bytes.Buffer
	types.WriteString(header + "package advernue\n\nimport \"encoding/json\"\n\nvar _ json.RawMessage\n\n")
	for _, n := range g.order {
		types.WriteString(g.types[n] + "\n")
	}
	types.Write(g.consts.Bytes())
	write(filepath.Join(*out, "types_gen.go"), types.Bytes())
	write(filepath.Join(*out, "services_gen.go"), svc)
	write(filepath.Join(*out, "CONTRIBUTING.md"), g.contributing(spec))
}

const header = "// Code generated by internal/cmd/generate from spec/openapi.json. DO NOT EDIT.\n\n"

func check(err error) {
	if err != nil {
		log.Fatal(err)
	}
}

func write(path string, b []byte) {
	if strings.HasSuffix(path, ".go") {
		f, err := format.Source(b)
		if err != nil {
			os.WriteFile(path+".broken", b, 0o644)
			log.Fatalf("%s: %v", path, err)
		}
		b = f
	}
	check(os.WriteFile(path, b, 0o644))
}

func keys(m schema) []string {
	r := make([]string, 0, len(m))
	for k := range m {
		r = append(r, k)
	}
	sort.Strings(r)
	return r
}

var acronyms = map[string]string{"id": "ID", "url": "URL", "api": "API", "utm": "UTM", "ip": "IP", "ws": "WS", "sig": "Sig", "exp": "Exp"}

// pascal turns "client_id", "clientId", "creativeLibrary" into Go identifiers.
func pascal(s string) string {
	var parts []string
	cur := []rune{}
	flush := func() {
		if len(cur) > 0 {
			parts = append(parts, string(cur))
			cur = cur[:0]
		}
	}
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			if len(cur) > 0 && !(cur[len(cur)-1] >= 'A' && cur[len(cur)-1] <= 'Z') {
				flush()
			}
			cur = append(cur, r)
		case r >= 'a' && r <= 'z' || r >= '0' && r <= '9':
			cur = append(cur, r)
		default:
			flush()
		}
	}
	flush()
	var b strings.Builder
	for _, p := range parts {
		if a, ok := acronyms[strings.ToLower(p)]; ok && a == strings.ToUpper(p) || ok && p == strings.ToLower(p) {
			b.WriteString(a)
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	r := b.String()
	if r == "" || r[0] >= '0' && r[0] <= '9' {
		r = "X" + r
	}
	return r
}

func lowerCamel(s string) string {
	p := pascal(s)
	r := strings.ToLower(p[:1]) + p[1:]
	if strings.HasPrefix(p, "ID") {
		r = "id" + p[2:]
	}
	switch r {
	case "type", "func", "var", "range", "package", "go", "map", "select", "default":
		r += "_"
	}
	return r
}

func (g *gen) unique(name string) string {
	base, i := name, 2
	for {
		if _, ok := g.types[name]; !ok {
			return name
		}
		name = fmt.Sprintf("%s%d", base, i)
		i++
	}
}

func refName(r string) string { return r[strings.LastIndex(r, "/")+1:] }

// goType returns the Go type expression for s; named inline objects are
// declared under hint. isStruct reports whether the result is a struct type
// (callers pass it by pointer).
func (g *gen) goType(s schema, hint string) (expr string, nullable bool) {
	if r, ok := s["$ref"].(string); ok {
		return refName(r), false
	}
	if a, ok := s["anyOf"].([]any); ok {
		var rest []schema
		null := false
		for _, x := range a {
			m := x.(schema)
			if m["type"] == "null" {
				null = true
			} else {
				rest = append(rest, m)
			}
		}
		if len(rest) == 1 {
			e, n := g.goType(rest[0], hint)
			return e, n || null
		}
		return "json.RawMessage", null
	}
	if _, ok := s["oneOf"]; ok {
		return "json.RawMessage", false
	}
	t := s["type"]
	if arr, ok := t.([]any); ok { // e.g. ["string","null"]
		var base string
		null := false
		for _, x := range arr {
			if x == "null" {
				null = true
			} else {
				base = x.(string)
			}
		}
		c := cloneWith(s, "type", base)
		e, _ := g.goType(c, hint)
		return e, null
	}
	switch t {
	case "string":
		return "string", false
	case "integer":
		return "int64", false
	case "number":
		return "float64", false
	case "boolean":
		return "bool", false
	case "array":
		it, _ := s["items"].(schema)
		if it == nil {
			return "[]json.RawMessage", false
		}
		e, n := g.goType(it, hint+"Item")
		return "[]" + pointerize(e, n), false
	case "object":
		props, _ := s["properties"].(schema)
		if len(props) == 0 {
			ap := s["additionalProperties"]
			if m, ok := ap.(schema); ok && len(m) > 0 {
				e, _ := g.goType(m, hint+"Value")
				return "map[string]" + e, false
			}
			return "json.RawMessage", false
		}
		return g.declare(g.unique(hint), s), false
	}
	return "json.RawMessage", false
}

func pointerize(e string, n bool) string {
	if n && !strings.HasPrefix(e, "[]") && !strings.HasPrefix(e, "map[") && e != "json.RawMessage" {
		return strings.TrimPrefix("*"+e, "**")
	}
	return e
}

func cloneWith(s schema, k string, v any) schema {
	c := schema{}
	for a, b := range s {
		c[a] = b
	}
	c[k] = v
	return c
}

// declare registers a named type for s and returns its name.
func (g *gen) declare(name string, s schema) string {
	if _, ok := g.types[name]; ok && !g.skip[name] {
		return name
	}
	g.types[name] = "" // reserve (recursion guard)
	g.order = append(g.order, name)
	var b strings.Builder
	doc := ""
	if d, ok := s["description"].(string); ok {
		doc = "// " + name + " - " + oneLine(d) + "\n"
	}
	props, _ := s["properties"].(schema)
	switch {
	case s["type"] == "string" && s["enum"] != nil:
		b.WriteString(doc + "type " + name + " string\n")
		for _, v := range s["enum"].([]any) {
			fmt.Fprintf(&g.consts, "const %s%s %s = %q\n", name, pascal(fmt.Sprint(v)), name, v)
		}
	case s["type"] == "object" && len(props) > 0:
		req := map[string]bool{}
		for _, r := range asList(s["required"]) {
			req[r.(string)] = true
		}
		b.WriteString(doc + "type " + name + " struct {\n")
		used := map[string]bool{}
		// keep spec property order is unavailable (map); sort for stability
		for _, k := range keys(props) {
			p := props[k].(schema)
			e, null := g.goType(p, name+pascal(k))
			fn := pascal(k)
			for used[fn] {
				fn += "_"
			}
			used[fn] = true
			tag := k
			if !req[k] || null {
				e = pointerize(e, true)
				tag += ",omitempty"
			}
			if d, ok := p["description"].(string); ok {
				fmt.Fprintf(&b, "\t// %s\n", oneLine(d))
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", fn, e, tag)
		}
		b.WriteString("}\n")
	default:
		e, _ := g.goType(s, name)
		if e == name {
			e = "json.RawMessage"
		}
		b.WriteString(doc + "type " + name + " " + e + "\n")
	}
	g.types[name] = b.String()
	return name
}

func asList(v any) []any {
	l, _ := v.([]any)
	return l
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// isStructType reports whether name is a declared struct (pass by pointer).
func (g *gen) isStructType(e string) bool {
	if e == "Money" {
		return true
	}
	d, ok := g.types[e]
	return ok && strings.Contains(d, " struct {")
}

type param struct {
	name, goName, in string
	required         bool
	typ              string
}

type operation struct {
	id, tag, name, method, path, summary string
}

func (g *gen) services(spec schema) []byte {
	paths := spec["paths"].(schema)
	byTag := map[string][]string{}
	var body bytes.Buffer
	var ops []operation
	for _, p := range keys(paths) {
		item := paths[p].(schema)
		for _, m := range []string{"get", "post", "put", "patch", "delete"} {
			o, ok := item[m].(schema)
			if !ok {
				continue
			}
			tag := o["tags"].([]any)[0].(string)
			id := o["operationId"].(string)
			opName := pascal(strings.SplitN(id, ".", 2)[1])
			svc := pascal(tag)
			byTag[svc] = append(byTag[svc], opName)
			sum, _ := o["summary"].(string)
			ops = append(ops, operation{id, tag, opName, strings.ToUpper(m), p, sum})
			g.emitOp(&body, svc, opName, strings.ToUpper(m), p, o)
		}
	}
	var out bytes.Buffer
	out.WriteString(header + "package advernue\n\nimport (\n\t\"context\"\n\t\"fmt\"\n\t\"net/url\"\n\t\"encoding/json\"\n)\n\nvar (\n\t_ = fmt.Sprint\n\t_ json.RawMessage\n\t_ url.Values\n)\n\n")
	svcs := keys(toSchema(byTag))
	out.WriteString("type services struct {\n")
	for _, s := range svcs {
		fmt.Fprintf(&out, "\t%s *%sService\n", s, s)
	}
	out.WriteString("}\n\nfunc (c *Client) initServices() {\n")
	for _, s := range svcs {
		fmt.Fprintf(&out, "\tc.%s = &%sService{c}\n", s, s)
	}
	out.WriteString("}\n\n")
	for _, s := range svcs {
		fmt.Fprintf(&out, "// %sService groups the %q operations.\ntype %sService struct{ c *Client }\n\n", s, s, s)
	}
	out.Write(body.Bytes())
	// types declared while emitting operations are written by main after this.
	return out.Bytes()
}

func toSchema(m map[string][]string) schema {
	r := schema{}
	for k := range m {
		r[k] = true
	}
	return r
}

func (g *gen) emitOp(w *bytes.Buffer, svc, name, method, path string, o schema) {
	prefix := svc + name
	var params, query []param
	idem, dry := false, false
	for _, x := range asList(o["parameters"]) {
		p := x.(schema)
		pn, in := p["name"].(string), p["in"].(string)
		req, _ := p["required"].(bool)
		switch {
		case in == "header" && pn == "Idempotency-Key":
			idem = true
		case in == "query" && pn == "dry_run":
			dry = true
		case in == "path":
			params = append(params, param{name: pn, goName: lowerCamel(pn), in: in, required: true})
		case in == "query":
			e, _ := g.goType(p["schema"].(schema), prefix+pascal(pn))
			query = append(query, param{name: pn, goName: pascal(pn), in: in, required: req, typ: e})
		}
	}
	// request body
	bodyType := ""
	if rb, ok := o["requestBody"].(schema); ok {
		if c, ok := rb["content"].(schema)["application/json"].(schema); ok {
			e, _ := g.goType(c["schema"].(schema), prefix+"Request")
			if g.isStructType(e) {
				e = "*" + e
			}
			bodyType = e
		}
	}
	// response
	respType, raw := "", false
	resps := o["responses"].(schema)
	for _, code := range keys(resps) {
		if code[0] != '2' {
			continue
		}
		r := resps[code].(schema)
		c, ok := r["content"].(schema)
		if !ok {
			continue
		}
		if j, ok := c["application/json"].(schema); ok {
			e, _ := g.goType(j["schema"].(schema), prefix+"Response")
			respType = e
		} else {
			raw = true
		}
		break
	}
	noAuth := false
	if sec, ok := o["security"].([]any); ok && len(sec) == 0 {
		noAuth = true
	}

	if len(query) > 0 {
		fmt.Fprintf(w, "// %sParams are the query parameters of %s.\ntype %sParams struct {\n", prefix, o["operationId"], prefix)
		for _, q := range query {
			t := q.typ
			if !q.required {
				t = "*" + t
			}
			fmt.Fprintf(w, "\t%s %s\n", q.goName, t)
		}
		fmt.Fprintf(w, "}\n\nfunc (p *%sParams) values() url.Values {\n\tq := url.Values{}\n\tif p == nil {\n\t\treturn q\n\t}\n", prefix)
		for _, q := range query {
			if q.required {
				fmt.Fprintf(w, "\tq.Set(%q, fmt.Sprint(p.%s))\n", q.name, q.goName)
			} else {
				fmt.Fprintf(w, "\tif p.%s != nil {\n\t\tq.Set(%q, fmt.Sprint(*p.%s))\n\t}\n", q.goName, q.name, q.goName)
			}
		}
		w.WriteString("\treturn q\n}\n\n")
	}

	args := "ctx context.Context"
	var kv []string
	for _, p := range params {
		args += ", " + p.goName + " string"
		kv = append(kv, fmt.Sprintf("%q, %s", p.name, p.goName))
	}
	qexpr := "nil"
	if len(query) > 0 {
		args += fmt.Sprintf(", params *%sParams", prefix)
		qexpr = "params.values()"
	}
	bexpr := "nil"
	if bodyType != "" {
		args += ", body " + bodyType
		bexpr = "body"
	}
	args += ", opts ...CallOption"
	ret := "error"
	call := "_, err := "
	outDecl, outArg := "", "nil"
	switch {
	case raw:
		ret, call = "([]byte, error)", "return "
		outArg = "RAW"
	case respType != "":
		pt := respType
		if g.isStructType(respType) {
			pt = "*" + respType
		}
		ret = "(" + pt + ", error)"
		if g.isStructType(respType) {
			outDecl = "out := new(" + respType + ")\n"
			outArg = "out"
		} else {
			outDecl = "var out " + respType + "\n"
			outArg = "&out"
		}
	}
	fmt.Fprintf(w, "// %s: %s (%s %s).\nfunc (s *%sService) %s(%s) %s {\n", name, o["summary"], method, path, svc, name, args, ret)
	spec := fmt.Sprintf("op{method: %q, path: expand(%q%s), query: %s, idem: %v, dry: %v, noAuth: %v}", method, path, joinPre(kv), qexpr, idem, dry, noAuth)
	switch {
	case raw:
		fmt.Fprintf(w, "\treturn s.c.doRaw(ctx, %s, %s, opts)\n}\n\n", spec, bexpr)
	case respType != "":
		fmt.Fprintf(w, "\t%sif err := s.c.do(ctx, %s, %s, opts, %s); err != nil {\n\t\treturn %s, err\n\t}\n\treturn %s, nil\n}\n\n", outDecl, spec, bexpr, outArg, zero(respType, g.isStructType(respType)), derefIf(outArg))
	default:
		fmt.Fprintf(w, "\treturn s.c.do(ctx, %s, %s, opts, nil)\n}\n\n", spec, bexpr)
	}
	_ = call
	_ = outDecl
}

func derefIf(a string) string {
	if a == "&out" {
		return "out"
	}
	return a
}

func zero(t string, st bool) string {
	if st {
		return "nil"
	}
	if strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[") || t == "json.RawMessage" {
		return "nil"
	}
	switch t {
	case "string":
		return `""`
	case "bool":
		return "false"
	case "int64", "float64":
		return "0"
	}
	return t + "{}" // named non-struct types (string enums, aliases)
}

func joinPre(kv []string) string {
	if len(kv) == 0 {
		return ""
	}
	return ", " + strings.Join(kv, ", ")
}

func (g *gen) contributing(spec schema) []byte {
	paths := spec["paths"].(schema)
	type row struct{ id, m, p, s string }
	by := map[string][]row{}
	n := 0
	for _, p := range keys(paths) {
		for _, m := range []string{"get", "post", "put", "patch", "delete"} {
			if o, ok := paths[p].(schema)[m].(schema); ok {
				tag := o["tags"].([]any)[0].(string)
				s, _ := o["summary"].(string)
				by[tag] = append(by[tag], row{o["operationId"].(string), strings.ToUpper(m), p, s})
				n++
			}
		}
	}
	var b bytes.Buffer
	b.WriteString("<!-- Generated by internal/cmd/generate from spec/openapi.json. DO NOT EDIT. -->\n\n# Contributing\n\n")
	fmt.Fprintf(&b, "Thanks for helping. This SDK wraps %d operations in %d services of the Advernue API (spec version %s).\n\n", n, len(by), spec["info"].(schema)["version"])
	b.WriteString(`## How the code is laid out

- Hand-written runtime: ` + "`client.go`, `options.go`, `errors.go`, `money.go`" + `.
- Generated, never edit by hand: ` + "`types_gen.go`, `services_gen.go`, and this file" + `.
- Generator: ` + "`internal/cmd/generate`" + ` (stdlib only). It reads ` + "`spec/openapi.json`" + `.

## Changing the API surface

1. Replace ` + "`spec/openapi.json`" + ` with the new spec.
2. Run ` + "`go generate ./...`" + `.
3. Run ` + "`go vet ./... && go test -race ./...`" + ` and commit the regenerated files with the spec.

The generated files are committed, so always regenerate before you push.

Service names come from the operation tag and method names from the part of the operationId after the dot (` + "`campaigns.list`" + ` becomes ` + "`client.Campaigns.List`" + `).

## Operations
`)
	for _, t := range keys(toSchema2(by)) {
		fmt.Fprintf(&b, "\n### %s\n\n| Method | Path | Operation | Go call |\n|---|---|---|---|\n", t)
		for _, r := range by[t] {
			fmt.Fprintf(&b, "| %s | `%s` | `%s` | `client.%s.%s` |\n", r.m, r.p, r.id, pascal(t), pascal(strings.SplitN(r.id, ".", 2)[1]))
		}
	}
	return b.Bytes()
}

func toSchema2[T any](m map[string]T) schema {
	r := schema{}
	for k := range m {
		r[k] = true
	}
	return r
}
